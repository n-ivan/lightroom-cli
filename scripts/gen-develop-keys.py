#!/usr/bin/env python3
"""Regenerates plugin/lrcli.lrdevplugin/DevelopKeys.lua from the Lightroom SDK docs.

Usage: scripts/gen-develop-keys.py [path/to/LrPhoto.html]

The default input is local/sdk/API Reference/modules/LrPhoto.html (the SDK is
untracked). The key list is the return-value paragraph of photo:getDevelopSettings.
"""
import html
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_INPUT = ROOT / "local/sdk/API Reference/modules/LrPhoto.html"
OUTPUT = ROOT / "plugin/lrcli.lrdevplugin/DevelopKeys.lua"

# The docs contain these typos; each correct spelling appears in the same SDK's
# LrDevelopController.html parameter lists (or, for Contrast2012, in the
# unsuffixed "Contrast: (number)" line of the same list).
RENAMES = {
    "HueAdjustmentMagenha": "HueAdjustmentMagenta",
    "LuminanceAdjustmentAque": "LuminanceAdjustmentAqua",
    "Parametriclights": "ParametricLights",
}
RETYPES = {"Contrast2012": "number"}

# Develop parameters from LrDevelopController.html's adjustPanel that the
# getDevelopSettings list omits although Lightroom returns and accepts them.
SUPPLEMENT = {"Temperature": "number", "Tint": "number", "Texture": "number"}


def develop_settings_section(page: str) -> str:
    start = page.index('<a name="photo:getDevelopSettings">')
    end = page.index('<a name="photo:getDevelopSnapshots">', start)
    section = re.sub(r"<[^>]+>", " ", page[start:end])
    return html.unescape(section)


def parse(section: str) -> dict:
    keys = {}
    for name, kind in re.findall(r"\b([A-Za-z][A-Za-z0-9]*)\s*:\s*\((\w+)\)", section):
        name = RENAMES.get(name, name)
        keys[name] = RETYPES.get(name, kind.lower())
    for name, kind in SUPPLEMENT.items():
        keys.setdefault(name, kind)
    return keys


def render(keys: dict) -> str:
    lines = [
        "-- GENERATED by scripts/gen-develop-keys.py from the Lightroom SDK docs",
        "-- (photo:getDevelopSettings in LrPhoto.html). Do not edit by hand.",
        "return {",
    ]
    lines += [f"  {name} = '{keys[name]}'," for name in sorted(keys)]
    lines.append("}")
    return "\n".join(lines) + "\n"


def main() -> None:
    source = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_INPUT
    keys = parse(develop_settings_section(source.read_text(encoding="utf-8")))
    OUTPUT.write_text(render(keys), encoding="utf-8")
    print(f"wrote {len(keys)} keys to {OUTPUT}")


if __name__ == "__main__":
    main()
