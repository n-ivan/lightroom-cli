#!/usr/bin/env python3
"""Regenerates plugin/lrcli.lrdevplugin/DevelopRanges.lua from saved `develop_ranges` output.

Usage: scripts/gen-develop-ranges.py [raw.json [nonraw.json]]

Defaults are scripts/data/develop-ranges-raw.json and develop-ranges-nonraw.json.
Produce them with `lrcli raw develop_ranges '{"photos":[<id>]}'` on a raw photo
and on a non-raw one (e.g. a TIFF), saving the JSON reply to those files.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "scripts/data"
OUTPUT = ROOT / "plugin/lrcli.lrdevplugin/DevelopRanges.lua"


def number(value) -> str:
    return str(int(value)) if float(value).is_integer() else repr(float(value))


def render_table(name: str, ranges: dict) -> list:
    lines = [f"  {name} = {{"]
    for key in sorted(ranges):
        low, high = ranges[key]
        lines.append(f"    {key} = {{ {number(low)}, {number(high)} }},")
    lines.append("  },")
    return lines


def load(path: Path) -> dict:
    reply = json.loads(path.read_text(encoding="utf-8"))
    if not reply.get("ok") or reply.get("failed"):
        sys.exit(f"{path}: reply is not ok or lists failed keys: {reply.get('failed')}")
    return reply["ranges"]


def main() -> None:
    raw_path = Path(sys.argv[1]) if len(sys.argv) > 1 else DATA / "develop-ranges-raw.json"
    nonraw_path = Path(sys.argv[2]) if len(sys.argv) > 2 else DATA / "develop-ranges-nonraw.json"
    raw, nonraw = load(raw_path), load(nonraw_path)
    lines = [
        "-- GENERATED by scripts/gen-develop-ranges.py from LrDevelopController.getRange",
        "-- results saved by `lrcli raw develop_ranges` (scripts/data/). Do not edit by hand.",
        "return {",
    ]
    lines += render_table("raw", raw)
    lines += render_table("nonRaw", nonraw)
    lines.append("}")
    OUTPUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {len(raw)} raw and {len(nonraw)} non-raw ranges to {OUTPUT}")


if __name__ == "__main__":
    main()
