#!/usr/bin/env python3
"""Regenerates plugin/lrcli.lrdevplugin/DevelopPanels.lua from the Lightroom SDK docs.

Usage: scripts/gen-develop-panels.py [path/to/LrDevelopController.html]

The default input is local/sdk/API Reference/modules/LrDevelopController.html
(the SDK is untracked). Panels come from its "Parameters in panels" list.
Controller names are mapped to getDevelopSettings keys using DevelopKeys.lua and
scripts/data/develop-ranges-raw.json; names without a numeric range (tables such
as ToneCurve and PointColors) and names without a range are dropped; panels left empty
(Lens Blur) are omitted.
"""
import html
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_INPUT = ROOT / "local/sdk/API Reference/modules/LrDevelopController.html"
KEYS = ROOT / "plugin/lrcli.lrdevplugin/DevelopKeys.lua"
RANGES = ROOT / "scripts/data/develop-ranges-raw.json"
NONRAW_RANGES = ROOT / "scripts/data/develop-ranges-nonraw.json"
OUTPUT = ROOT / "plugin/lrcli.lrdevplugin/DevelopPanels.lua"

TITLES = {
    "adjustPanel": "Basic",
    "tonePanel": "Tone Curve",
    "mixerPanel": "Color Mixer (HSL / B&W)",
    "colorGradingPanel": "Color Grading",
    "detailPanel": "Detail",
    "effectsPanel": "Effects",
    "lensCorrectionsPanel": "Lens Corrections",
    "calibratePanel": "Calibration",
    "lensBlurPanel": "Lens Blur",
}

# Controller-only or ineffective: applyDevelopSettings cannot set the first two,
# and the docs say Brightness has no effect in the current process version.
EXCLUDED = {"PresetAmount", "ProfileAmount", "Brightness"}

# getDevelopSettings keys, not controller names, so they are not parsed from the docs.
CROP_KEYS = ["CropLeft", "CropRight", "CropTop", "CropBottom", "CropAngle"]
# Non-raw photos use these instead of Temperature/Tint (see Writes.rangeError).
BASIC_EXTRA = ["IncrementalTemperature", "IncrementalTint"]


def panel_section(page: str) -> str:
    start = page.index("Parameters in panels")
    end = page.index("Crop Angle", start)
    return html.unescape(re.sub(r"<[^>]+>", " ", page[start:end]))


def parse_panels(section: str) -> dict:
    panels = {}
    for panel_id, body in re.findall(r"(\w+Panel)\s*=\s*\{(.*?)\}", section, re.S):
        panels[panel_id] = re.findall(r'"([A-Za-z0-9]+)"', body)
    return panels


def load_known() -> tuple:
    keys = set(re.findall(r"^\s*(\w+) = '", KEYS.read_text(encoding="utf-8"), re.M))
    ranged = set()
    for path in (RANGES, NONRAW_RANGES):
        ranged |= set(json.loads(path.read_text(encoding="utf-8"))["ranges"])
    return keys, ranged


def map_name(name: str, known: tuple):
    keys, ranged = known
    if name in EXCLUDED:
        return None
    if name + "2012" in keys | ranged:
        return name + "2012"
    return name if name in ranged else None


def lua_string(text: str) -> str:
    return "'" + text.replace("\\", "\\\\").replace("'", "\\'") + "'"


def build(panels: dict, known: tuple) -> list:
    result = []
    for panel_id, title in TITLES.items():
        keys = []
        for name in panels[panel_id]:
            key = map_name(name, known)
            if key and key not in keys:
                keys.append(key)
        if panel_id == "adjustPanel":
            keys += [k for k in BASIC_EXTRA if k not in keys]
        if keys:
            result.append((panel_id, title, keys))
    result.append(("crop", "Crop", CROP_KEYS))
    return result


def render(panels: list) -> str:
    lines = [
        "-- GENERATED by scripts/gen-develop-panels.py from the Lightroom SDK docs",
        "-- (LrDevelopController.html, \"Parameters in panels\"). Do not edit by hand.",
        "return {",
    ]
    for panel_id, title, keys in panels:
        lines.append(f"  {{ id = {lua_string(panel_id)}, title = {lua_string(title)}, keys = {{")
        lines += [f"    {lua_string(key)}," for key in keys]
        lines.append("  } },")
    lines.append("}")
    return "\n".join(lines) + "\n"


def main() -> None:
    source = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_INPUT
    panels = parse_panels(panel_section(source.read_text(encoding="utf-8")))
    missing = [p for p in TITLES if p not in panels]
    if missing:
        sys.exit(f"panels not found in {source}: {', '.join(missing)}")
    known = load_known()
    result = build(panels, known)
    for panel_id in TITLES:
        dropped = [n for n in panels[panel_id] if map_name(n, known) is None]
        if dropped:
            print(f"{panel_id}: dropped {', '.join(dropped)}")
    OUTPUT.write_text(render(result), encoding="utf-8")
    print(f"wrote {len(result)} panels to {OUTPUT}")


if __name__ == "__main__":
    main()
